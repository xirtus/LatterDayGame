import assert from 'node:assert/strict';
import {chromium} from 'playwright';

const browser = await chromium.launch({headless: true});
const context = await browser.newContext({viewport: {width: 1280, height: 800}});
await context.addInitScript(() => localStorage.setItem('gathering-of-zion:v1:settings', JSON.stringify({quality: 'low', sound: false, reducedMotion: true})));
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const state = () => page.evaluate(() => ({...window.zionGame.getState(), encounter: window.zionGame.getEncounters()}));
const ready = () => page.waitForFunction(() => window.zionGame?.getState().ready, null, {timeout: 90000});
const simulate = async duration => {
  const start = (await state()).encounter.time;
  await page.waitForFunction(target => window.zionGame.getEncounters().time >= target, start + duration, {timeout: 45000});
};
const results = [];
try {
  await page.goto(process.env.GAME_URL ?? 'http://127.0.0.1:8923/game/');
  await page.waitForFunction(() => window.zionGame, null, {timeout: 90000});
  await page.click('#begin');
  await ready();
  await page.evaluate(() => window.zionGame.enterChapter('BM03'));
  await ready();
  let initial = await state();
  assert.equal(initial.encounter.kind, 'treasury');
  assert.equal(initial.encounter.managedActorIds.length, 2);
  const sentryStart = initial.encounter.actors.find(actor => actor.id === 'TREASURY_SENTRY_0').position;
  await page.keyboard.press('KeyC');
  await page.keyboard.down('KeyW');
  await simulate(.7);
  await page.keyboard.up('KeyW');
  let current = await state();
  assert(current.encounter.crouching);
  const quietSpeed = Math.hypot(current.player[0] - initial.player[0], current.player[2] - initial.player[2]) / (current.encounter.time - initial.encounter.time);
  assert(quietSpeed > .95 && quietSpeed < 1.65, `quiet movement: ${quietSpeed}`);
  await page.keyboard.press('KeyC');
  initial = await state();
  await page.keyboard.down('KeyW');
  await simulate(.7);
  await page.keyboard.up('KeyW');
  current = await state();
  const walkSpeed = Math.hypot(current.player[0] - initial.player[0], current.player[2] - initial.player[2]) / (current.encounter.time - initial.encounter.time);
  assert(walkSpeed > 2.1 && walkSpeed < 2.9, `walking: ${walkSpeed}`);
  assert(walkSpeed > quietSpeed * 1.45);
  await simulate(1.2);
  current = await state();
  assert.notDeepEqual(current.encounter.actors.find(actor => actor.id === 'TREASURY_SENTRY_0').position, sentryStart);
  await page.keyboard.press('KeyH');
  await page.keyboard.press('KeyF');
  current = await state();
  assert.equal(current.encounter.combatEnabled, false);
  assert.equal(current.encounter.player.swing, 0);
  assert.equal(current.encounter.player.health, 100);
  results.push({chapter: 'BM03', quietSpeed, walkSpeed, sentriesPatrolling: true, sourceCombatLocked: true});

  await page.evaluate(() => window.zionGame.enterChapter('BM24'));
  await ready();
  await page.keyboard.press('KeyH');
  await page.keyboard.press('KeyF');
  current = await state();
  assert.equal(current.encounter.combatEnabled, true);
  assert.equal(current.encounter.player.swing, 1);
  assert(current.encounter.player.stamina < 100);
  await simulate(1.1);
  await page.keyboard.down('KeyG');
  await simulate(.25);
  current = await state();
  assert(current.encounter.guarding);
  assert.equal(current.encounter.player.phase, 'guard');
  await page.keyboard.up('KeyG');
  await simulate(.1);
  initial = await state();
  await page.keyboard.press('KeyQ');
  current = await state();
  assert(Math.hypot(current.player[0] - initial.player[0], current.player[2] - initial.player[2]) > .7);
  assert(current.encounter.player.stamina < initial.encounter.player.stamina);
  assert(current.encounter.actors.filter(actor => !actor.managed).every(actor => actor.combat.protected));
  await page.locator('[data-encounter-action="skip"]').click();
  current = await state();
  assert.equal(current.encounter.challenge, false);
  assert.equal(current.encounter.sourceOutcomeLocked, true);
  const save = await page.evaluate(() => JSON.parse(localStorage.getItem('gathering-of-zion:v1')));
  assert(save.version === 4 && save.encounterProgress?.BM24);
  results.push({chapter: 'BM24', normalInputStrike: true, heldGuard: true, withdrawal: true, sourceActorsProtected: true, assistAndSave: true});
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({passed: results.length, results, errors}, null, 2));
} finally {
  await browser.close();
}
