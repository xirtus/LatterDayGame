import assert from 'node:assert/strict';
import {mkdir, writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';

const browser = await chromium.launch({headless: true});
const context = await browser.newContext({viewport: {width: 1280, height: 800}});
await context.addInitScript(() => localStorage.setItem('gathering-of-zion:v1:settings', JSON.stringify({quality: 'low', sound: false, reducedMotion: true, reducedFlash: true})));
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const ready = () => page.waitForFunction(() => window.zionGame?.getState().ready, null, {timeout: 120000});
const state = () => page.evaluate(() => ({...window.zionGame.getState(), encounter: window.zionGame.getEncounters(), light: window.zionGame.getLighting()}));
const results = [];
await mkdir('game/evidence/living-worlds', {recursive: true});
async function finishObjective() {
  const before = (await state()).objective;
  await page.evaluate(() => { window.zionGame.teleportToObjective(); window.zionGame.interact(); });
  for (let index = 0; index < 30 && (await state()).dialogue >= 0; index++) await page.evaluate(() => window.zionGame.advanceDialogue());
  await ready();
  assert.equal((await state()).objective, before + 1);
}
try {
  await page.goto((process.env.GAME_URL ?? 'http://127.0.0.1:8923/game/') + '?chapter=08');
  await page.waitForFunction(() => window.zionGame, null, {timeout: 120000});
  await ready();
  assert.equal((await state()).light.chapterId, '08');
  await finishObjective();
  const scribe = await page.evaluate(() => ({pose: window.zionGame.getMotionDiagnostics().find(actor => actor.id === 'OLIVER'), position: window.zionGame.scene.getObjectByName('actor:OLIVER').position.toArray()}));
  assert(scribe.pose.seated, 'Oliver uses an actual seated state at his desk');
  assert.deepEqual(scribe.position, [3, 0, -3.2]);
  await page.evaluate(() => { window.zionGame.teleportToObjective(); window.zionGame.interact(); });
  const dialogueStart = (await state()).encounter.time;
  await page.waitForTimeout(500);
  assert.equal((await state()).encounter.time, dialogueStart, 'Conversations pause encounter clocks');
  const listening = await page.evaluate(() => window.zionGame.getMotionDiagnostics().find(actor => actor.id === 'OLIVER'));
  assert(listening.seated, 'Dialogue does not pop the seated scribe upright');
  await page.screenshot({path: 'game/evidence/living-worlds/translation-seated.png'});
  while ((await state()).dialogue >= 0) await page.evaluate(() => window.zionGame.advanceDialogue());
  results.push('Shared chapter lighting, seated translation work, seated dialogue and paused encounter clocks');

  await page.evaluate(() => window.zionGame.enterChapter('30'));
  await ready();
  await page.click('[data-encounter-action=skip]');
  assert((await page.evaluate(() => window.zionGame.getMotionDiagnostics().find(actor => actor.id === 'JOHN_TAYLOR'))).seated, 'Story assist preserves the seated hymn staging');
  results.push('Carthage story assist preserves the seated John Taylor blocking');

  await page.evaluate(() => window.zionGame.enterChapter('BM24'));
  await ready();
  assert.equal(await page.locator('#encounter-panel').isVisible(), true);
  await page.keyboard.press('KeyH');
  await page.keyboard.press('KeyF');
  let combat = (await state()).encounter;
  assert(combat.challenge && combat.combatEnabled);
  assert(combat.player.stamina < 100 && combat.player.swing > 0);
  assert(combat.playerEquipment.visible && combat.playerEquipment.blade && combat.playerEquipment.shield);
  await page.keyboard.press('KeyV');
  const fixed = (await state()).player;
  const swing = combat.player.swing;
  await page.keyboard.press('KeyF');
  await page.keyboard.press('KeyH');
  await page.keyboard.down('KeyW');
  await page.waitForTimeout(250);
  await page.keyboard.up('KeyW');
  combat = (await state()).encounter;
  assert.deepEqual((await state()).player, fixed);
  assert.equal(combat.player.swing, swing, 'Free camera never attacks');
  assert.equal(combat.challenge, true, 'Free camera never toggles a challenge');
  await page.keyboard.press('Digit3');
  await page.click('#menu-button');
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('gathering-of-zion:v1')));
  assert.equal(saved.version, 4);
  assert.equal(saved.encounterProgress.BM24.player.swing, swing);
  assert.deepEqual(saved.position, fixed);
  await page.evaluate(() => history.replaceState(null, '', '/game/'));
  await page.reload();
  await page.waitForFunction(() => window.zionGame, null, {timeout: 120000});
  await page.click('#resume');
  await ready();
  const resumed = await state();
  assert.equal(resumed.chapter, 'BM24');
  assert.equal(resumed.encounter.challenge, true);
  assert.equal(resumed.encounter.player.swing, swing);
  assert.deepEqual(resumed.player, fixed);
  results.push('Physical player equipment, actual challenge controls, free-camera isolation and version-4 encounter/position reload');

  await page.click('#settings-button');
  assert.equal(await page.locator('#reduced-flash').isChecked(), true);
  await page.selectOption('#quality', 'high');
  assert.equal((await state()).light.quality, 'high');
  await page.selectOption('#quality', 'low');
  assert.equal((await state()).light.quality, 'low');
  assert.equal(await page.evaluate(() => window.zionGame.scene.children.filter(object => object.name === 'shared-lighting-runtime').length), 1);
  await page.click('[data-close=settings]');
  await page.click('[data-encounter-action=skip]');
  assert.equal((await state()).encounter.challenge, false);
  assert.equal((await state()).encounter.playerEquipment.visible, false);
  await page.waitForFunction(() => window.zionGame.getMotionDiagnostics().find(actor => actor.id === window.zionGame.getState().playerId)?.motion === 'idle');
  await page.waitForTimeout(500);
  const playerMotion = await page.evaluate(() => window.zionGame.getMotionDiagnostics().find(actor => actor.id === window.zionGame.getState().playerId));
  await page.screenshot({path: 'game/evidence/living-worlds/cumorah-controls.png'});
  results.push('Live quality changes retain one lighting owner, reduced-flash default, story assist removes combat equipment');

  await page.setViewportSize({width: 390, height: 844});
  await page.waitForTimeout(250);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert(await page.locator('#challenge-action').isVisible());
  const bounds = await page.locator('#encounter-panel').boundingBox();
  assert(bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y >= 0 && bounds.y + bounds.height <= 844);
  await page.screenshot({path: 'game/evidence/living-worlds/mobile-encounter.png'});
  results.push('390-pixel encounter HUD fits viewport and exposes touch actions');
  await page.click('#settings-button');
  page.once('dialog', dialog => dialog.accept());
  await page.click('#reset-save');
  assert.equal(await page.evaluate(() => localStorage.getItem('gathering-of-zion:v1')), null);
  assert.equal(await page.locator('#resume').isVisible(), false);
  results.push('Reset journey does not immediately recreate the cleared save');
  assert.deepEqual(errors, []);
  await writeFile('game/evidence/living-worlds/integration.json', JSON.stringify({results, errors, scribe, playerMotion, note: 'WASD used for free-camera isolation; objective setup uses the debug teleport. Dedicated route suites separately verify real world traversal.'}, null, 2));
  console.log(JSON.stringify({passed: results.length, results, errors}, null, 2));
} finally {
  await browser.close();
}
