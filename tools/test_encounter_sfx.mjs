import assert from 'node:assert/strict';
import {createEncounterSFX} from '../game/src/encounters/sfx.js';

let sources = 0;
let disconnected = 0;
const parameter = () => ({value: 0, setValueAtTime() {}, linearRampToValueAtTime() {}, exponentialRampToValueAtTime() {}});
const node = () => ({gain: parameter(), frequency: parameter(), connect() {}, disconnect() { disconnected++; }, start() { sources++; }, stop() {}});
const context = {state: 'running', currentTime: 1, sampleRate: 8000, createGain: node, createBiquadFilter: node, createOscillator: node, createBufferSource: node, createBuffer: (channels, samples) => ({getChannelData: () => new Float32Array(samples)})};
const sound = {context, master: node(), enabled: true};
const powder = {id: 'carthage:report:1'};
const effects = createEncounterSFX(sound, {events: [powder]});
effects.update({events: [powder]});
assert.equal(sources, 0, 'Restored events do not replay audio');
effects.update({events: [{id: 'carthage:report:2'}]});
assert.equal(sources, 1);
effects.update({events: [{id: 'carthage:report:2'}]});
assert.equal(sources, 1, 'Reports deduplicate across status updates');
sound.enabled = false;
effects.update({events: [{id: 'carthage:report:3'}]});
assert.equal(sources, 1, 'Ambient mute includes effects');
sound.enabled = true;
effects.update({events: [{id: 'sword:1:target', result: 'blocked'}]});
assert.equal(sources, 2);
effects.dispose();
assert.equal(disconnected, 6, 'All owned nodes disconnect on scene teardown');
effects.update({events: [{id: 'carthage:report:4'}]});
assert.equal(sources, 2);
assert.equal(context.state, 'running', 'Shared audio context stays owned by the original soundscape');
console.log('PASS non-voice encounter effects: restored-event suppression, deduplication, mute, bounded nodes and cleanup; no recording access.');
